#!/usr/bin/env node
// Builds the cookie pop-up script for Calm Mode from DuckDuckGo's autoconsent (MPL-2.0):
// the self-contained "standalone" build (rules included), which rejects consent pop-ups in
// the page itself. Its console logging is switched off.
//   node scripts/gen-autoconsent.mjs   (re-run after upgrading @duckduckgo/autoconsent)
// Output: native/shield-webview/ios/Resources/vendor/autoconsent.js, bundled on iOS and
// copied into the Android assets by the module's build.gradle.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkgDir = path.join(root, 'node_modules/@duckduckgo/autoconsent');
const pkg = JSON.parse(fs.readFileSync(path.join(pkgDir, 'package.json'), 'utf8'));
let source = fs.readFileSync(path.join(pkgDir, 'dist/autoconsent.standalone.js'), 'utf8');

const replaceOnce = (from, to) => {
  if (!source.includes(from)) throw new Error(`autoconsent ${pkg.version}: expected text not found:\n${from}`);
  source = source.replace(from, to);
};

// No logging: turn every log switch off and drop the message logger and start-up notes.
source = source.replace(/logs: \{[^}]*\}/g, (block) => block.replace(/: true/g, ': false'));
replaceOnce('      logMessage(message);\n', '');
replaceOnce('console.log("autoconsent standalone initialized"', 'void ("autoconsent standalone initialized"');
replaceOnce('console.warn("autoconsent already initialized", window.autoconsentReceiveMessage);', '');
if (/logs: \{[^}]*true/.test(source)) throw new Error('autoconsent: logging still on');

const out = `// Generated by scripts/gen-autoconsent.mjs from @duckduckgo/autoconsent ${pkg.version}.
// Mozilla Public License 2.0: https://github.com/duckduckgo/autoconsent (source available there).
// Do not edit by hand.
${source}`;
const dest = path.join(root, 'native/shield-webview/ios/Resources/vendor/autoconsent.js');
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out);
console.log(`wrote ${path.relative(root, dest)} (${(out.length / 1024).toFixed(0)} KB, autoconsent ${pkg.version})`);
