#!/usr/bin/env node
// Embeds Mozilla Readability (Apache-2.0) as a string so reader mode can inject it.
//   node scripts/gen-readability.mjs   (re-run after upgrading @mozilla/readability)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'node_modules/@mozilla/readability/package.json'), 'utf8'));
const source = fs.readFileSync(path.join(root, 'node_modules/@mozilla/readability/Readability.js'), 'utf8');

const out = `// Generated by scripts/gen-readability.mjs from @mozilla/readability ${pkg.version} (Apache-2.0).
// Do not edit by hand.
export const READABILITY_VERSION = ${JSON.stringify(pkg.version)};
export const READABILITY_SOURCE = ${JSON.stringify(source)};
`;
fs.writeFileSync(path.join(root, 'src/browser/readability.generated.ts'), out);
console.log(`wrote src/browser/readability.generated.ts (${source.length} chars)`);
